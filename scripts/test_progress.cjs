const{chromium}=require('playwright'),assert=require('node:assert/strict');
(async()=>{
  const browser=await chromium.launch({channel:'chrome',headless:true});
  const page=await browser.newPage({viewport:{width:1440,height:900}}),errors=[];
  page.on('pageerror',error=>errors.push(error.message));
  await page.addInitScript(()=>sessionStorage.setItem('nebula-access-20261014-temp','granted'));
  await page.goto(process.env.NEBULA_TEST_URL||'http://localhost:8765');
  assert.equal(await page.locator('#show-progress').innerText(),'Tracking Progress');
  await page.click('#show-progress');
  assert.equal(await page.locator('#progress-view').isVisible(),true);
  assert.equal(await page.locator('#patient-strip').isVisible(),false);
  assert.equal(await page.locator('#case-actions').isVisible(),false);
  assert.deepEqual(await page.locator('.progress-chart-card h2').allTextContents(),['Labeled Patient Growth','Top 3 Score']);
  assert.equal(await page.locator('#patient-growth-chart circle.patient-point').count(),4);
  assert.equal(await page.locator('#top3-progress-chart circle.top3-point').count(),4);
  assert.equal(await page.locator('.progress-svg').count(),2);
  assert.ok(await page.locator('.progress-line').evaluateAll(lines=>lines.length===2&&lines.every(el=>getComputedStyle(el).strokeWidth==='2px'&&getComputedStyle(el).fill==='none')));
  assert.deepEqual(await page.locator('#top3-progress-chart .chart-tick-left').allTextContents(),['55%','60%','65%','70%','75%']);
  assert.equal(await page.locator('#progress-view table,#progress-view p,#progress-view article:not(.progress-chart-card)').count(),0);
  assert.deepEqual(errors,[]);
  await page.setViewportSize({width:390,height:844});
  assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1));
  await page.click('#show-scoring');assert.equal(await page.locator('#scoring-view').isVisible(),true);
  await browser.close();console.log('PASS: simplified patient-growth and Top 3 tracking charts with responsive navigation.');
})().catch(error=>{console.error(error);process.exit(1);});
